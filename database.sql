SHOW DATABASES;
USE asal_beautycare;

CREATE TABLE OnlineStore (
	   store_id int auto_increment primary key,
       store_name varchar(100) not null,
       website varchar(100),
       contact_email VARCHAR(100),
       contact_phone VARCHAR(20),
	   manager_name VARCHAR(100)
);

CREATE TABLE Staff (
    staff_id INT AUTO_INCREMENT PRIMARY KEY,
    Staff_name VARCHAR(100) NOT NULL,
    position VARCHAR(50),
    salary NUMERIC(10,2)
);

CREATE TABLE Category (
    category_id INT AUTO_INCREMENT PRIMARY KEY,
    Category_name VARCHAR(100) NOT NULL,
    Category_description TEXT
);

CREATE TABLE Supplier (
    supplier_id INT AUTO_INCREMENT PRIMARY KEY,
    Supplier_name VARCHAR(100) NOT NULL,
    contact_info VARCHAR(150),
    country VARCHAR(50)
);

CREATE TABLE Customer (
    customer_id INT AUTO_INCREMENT PRIMARY KEY,
    Customer_name VARCHAR(100) NOT NULL,
    Customer_phone VARCHAR(20),
    Customer_address VARCHAR(200)
);

CREATE TABLE Warehouse (
    warehouse_id INT AUTO_INCREMENT PRIMARY KEY,
    store_id INT,
    location VARCHAR(150),
    capacity INT,
    stock_manager VARCHAR(100),
    FOREIGN KEY (store_id) REFERENCES OnlineStore(store_id)
);

CREATE TABLE Product (
    product_id INT AUTO_INCREMENT PRIMARY KEY,
    category_id INT , 
    Product_name VARCHAR(100),
    price DECIMAL(10,2),
    brand VARCHAR(100),
    Product_description TEXT,
    FOREIGN KEY (category_id) REFERENCES Category(category_id)
);

CREATE TABLE Inventory (
     warehouse_id INT NOT NULL ,
     product_id INT NOT NULL,
     quantity INT NOT NULL,
     PRIMARY KEY (warehouse_id, product_id),
     FOREIGN KEY (warehouse_id) REFERENCES Warehouse(warehouse_id),
     FOREIGN KEY (product_id) REFERENCES Product(product_id)
);

create table Purchase(
     purchase_id INT AUTO_INCREMENT PRIMARY KEY,
     supplier_id INT,
     Purchase_date DATE DEFAULT (CURDATE()),
     total_cost NUMERIC(10,2) DEFAULT 0,
	 FOREIGN KEY (supplier_id) REFERENCES Supplier(supplier_id)
);

CREATE TABLE Orders (
    order_id INT AUTO_INCREMENT PRIMARY KEY,
    customer_id INT,
    order_date DATE DEFAULT (CURDATE()),
    status VARCHAR(20) DEFAULT 'pending',  
    total_amount DECIMAL(10,2) DEFAULT 0,
    discount DECIMAL(10,2) DEFAULT 0,
    final_amount DECIMAL(10,2) DEFAULT 0,
    payment_status VARCHAR(20) DEFAULT 'unpaid',  
    cost DECIMAL(10,2) DEFAULT 0,
    notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (customer_id) REFERENCES Customer(customer_id)
);

CREATE TABLE Order_Product (
    order_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity INT NOT NULL,
    price_at_order DECIMAL(10,2) NOT NULL,
    subtotal DECIMAL(10,2) GENERATED ALWAYS AS (quantity * price_at_order) STORED,
    PRIMARY KEY (order_id, product_id),
    FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    FOREIGN KEY (product_id) REFERENCES Product(product_id)
);

CREATE TABLE Payment (
    payment_id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL,  
    amount DECIMAL(10,2) NOT NULL,
    date DATE DEFAULT (CURDATE()),
    method VARCHAR(20),
    transaction_ref VARCHAR(100),
    FOREIGN KEY (order_id) REFERENCES Orders(order_id)
);

CREATE TABLE Delivery (
    delivery_id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL, 
    shipping_company VARCHAR(50),
    delivery_date DATE,
    status VARCHAR(20) DEFAULT 'pending',
    cost DECIMAL(10,2) DEFAULT 0,
    tracking_number VARCHAR(100),
    FOREIGN KEY (order_id) REFERENCES Orders(order_id)
);

create table Purchase_Item(
     item_id INT AUTO_INCREMENT PRIMARY KEY,
     purchase_id INT NOT NULL,
     product_id  INT NOT NULL,
     quantity  INT NOT NULL,
     cost_per_unit numeric(10,2) NOT NULL,
	 FOREIGN KEY (purchase_id) REFERENCES Purchase(purchase_id),
	 FOREIGN KEY (product_id) REFERENCES Product(product_id)
);

CREATE TABLE Returns (
    return_id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL,
    return_date DATE,
    reason VARCHAR(100),
    status VARCHAR(20) DEFAULT 'requested',
    refund_amount DECIMAL(10,2),
    FOREIGN KEY (order_id) REFERENCES Orders(order_id)
);

CREATE TABLE Return_Product (
    return_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity INT NOT NULL,
    refund_per_unit DECIMAL(10,2),
    PRIMARY KEY (return_id, product_id),
    FOREIGN KEY (return_id) REFERENCES Returns(return_id),
    FOREIGN KEY (product_id) REFERENCES Product(product_id)
);

CREATE TABLE staff_archive (
    staff_id INT PRIMARY KEY,
    staff_name VARCHAR(100),
    position VARCHAR(50),
    salary NUMERIC(10,2),
    archived_date DATE
);

CREATE TABLE purchase_archive (
    archive_id INT AUTO_INCREMENT PRIMARY KEY,
    purchase_id INT,
    supplier_id INT,
    total_price DOUBLE,
    purchase_date DATE,
    archived_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
DROP TABLE IF EXISTS purchase_archive;

CREATE TABLE purchase_archive (
    archive_id INT AUTO_INCREMENT PRIMARY KEY, 
    purchase_id INT,                          
    supplier_id INT,
    purchase_date DATE,
    total_cost DOUBLE,
    archived_date DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE returns_archive (
    return_id INT PRIMARY KEY,
    order_id INT,
    return_date DATE,
    reason VARCHAR(255),
    status VARCHAR(50),
    refund_amount DOUBLE,
    archived_date DATETIME DEFAULT CURRENT_TIMESTAMP
);

